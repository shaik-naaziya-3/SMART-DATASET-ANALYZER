from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle
)

from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib import colors


styles = getSampleStyleSheet()

pdf = SimpleDocTemplate("report.pdf")

elements = []


# ---------------- TITLE ----------------

elements.append(

    Paragraph(

        "SMART DATASET ANALYZER REPORT",

        styles["Title"]

    )

)

elements.append(Spacer(1, 20))


# ---------------- INTRODUCTION ----------------

elements.append(

    Paragraph(

        "This report is automatically generated by the Smart Dataset Analyzer after performing dataset analysis and AI model training.",

        styles["BodyText"]

    )

)

elements.append(Spacer(1, 20))


# ---------------- FEATURES ----------------

elements.append(

    Paragraph(

        "<b>Analysis Performed</b>",

        styles["Heading2"]

    )

)

elements.append(

    Paragraph(

        "&#8226; Dataset Upload<br/>"
        "&#8226; Dataset Analysis<br/>"
        "&#8226; Missing Value Detection<br/>"
        "&#8226; Duplicate Detection<br/>"
        "&#8226; Dataset Type Detection<br/>"
        "&#8226; AI Model Recommendation<br/>"
        "&#8226; Model Training<br/>"
        "&#8226; Model Comparison",

        styles["BodyText"]

    )

)

elements.append(Spacer(1, 20))


# ---------------- SAMPLE RESULT TABLE ----------------

table_data = [

    ["Parameter", "Value"],

    ["Dataset Status", "Successfully Processed"],

    ["Analysis", "Completed"],

    ["Training", "Completed"],

    ["Report", "Generated Successfully"]

]


table = Table(table_data)

table.setStyle(

    TableStyle([

        ("BACKGROUND", (0, 0), (-1, 0), colors.darkblue),

        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),

        ("GRID", (0, 0), (-1, -1), 1, colors.black),

        ("BACKGROUND", (0, 1), (-1, -1), colors.beige),

        ("ALIGN", (0, 0), (-1, -1), "CENTER"),

        ("BOTTOMPADDING", (0, 0), (-1, 0), 10),

    ])

)

elements.append(table)

elements.append(Spacer(1, 25))


# ---------------- FOOTER ----------------

elements.append(

    Paragraph(

        "Generated by Smart Dataset Analyzer",

        styles["Italic"]

    )

)


pdf.build(elements)

print("REPORT GENERATED")